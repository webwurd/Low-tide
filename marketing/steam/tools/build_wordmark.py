#!/usr/bin/env python3
"""Outline the Low Tide wordmark from Marcellus (SIL OFL) into marketing/steam/wordmark.js.

Kerned with HarfBuzz, then tracked. The "I" in TIDE is exported separately because it is
the lighthouse: the logo puts the lamp above it.

Usage: python3 build_wordmark.py [path/to/Marcellus-Regular.ttf]
With no argument the font is fetched from Google Fonts.
Requires: pip install fonttools uharfbuzz
"""
import json, re, sys, urllib.request
from pathlib import Path
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

TRACK = 215        # letter-spacing, font units per 1000
WORD_GAP = 600     # between LOW and TIDE, measured edge to edge of advances
OUT = Path(__file__).resolve().parent.parent / "wordmark.js"


def fetch_font() -> Path:
    css = urllib.request.urlopen(urllib.request.Request(
        "https://fonts.googleapis.com/css2?family=Marcellus",
        headers={"User-Agent": "Mozilla/5.0"})).read().decode()
    url = re.search(r"url\((https://[^)]+\.ttf)\)", css).group(1)
    dst = Path("/tmp/Marcellus-Regular.ttf")
    dst.write_bytes(urllib.request.urlopen(url).read())
    return dst


def n(v):
    return ("%.1f" % v).rstrip("0").rstrip(".")


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else fetch_font()
    tt = TTFont(path)
    gs, order = tt.getGlyphSet(), tt.getGlyphOrder()
    upm = tt["head"].unitsPerEm
    k = 1000 / upm
    cap = tt["OS/2"].sCapHeight * k

    blob = hb.Blob.from_file_path(str(path))
    hbfont = hb.Font(hb.Face(blob))

    def shape(word):
        buf = hb.Buffer(); buf.add_str(word); buf.guess_segment_properties()
        hb.shape(hbfont, buf, {"kern": True})
        return buf.glyph_infos, buf.glyph_positions

    pen = SVGPathPen(gs, ntos=n)
    x = 0.0
    i_cx = None
    for wi, word in enumerate(("LOW", "TIDE")):
        infos, poss = shape(word)
        pen_x = x
        for ci, (info, pos) in enumerate(zip(infos, poss)):
            name = order[info.codepoint]
            # y flipped: baseline at 0, cap line at -cap (SVG space)
            gs[name].draw(TransformPen(pen, (k, 0, 0, -k, pen_x + pos.x_offset * k, 0)))
            if word == "TIDE" and word[ci] == "I":
                bp = BoundsPen(gs); gs[name].draw(bp)
                i_cx = pen_x + (bp.bounds[0] + bp.bounds[2]) / 2 * k
            pen_x += pos.x_advance * k + (TRACK if ci < len(infos) - 1 else 0)
        x = pen_x + (WORD_GAP if wi == 0 else 0)
    total = x

    # the I on its own, centred on x=0
    ipen = SVGPathPen(gs, ntos=n)
    iname = tt.getBestCmap()[ord("I")]
    bp = BoundsPen(gs); gs[iname].draw(bp)
    icx = (bp.bounds[0] + bp.bounds[2]) / 2 * k
    gs[iname].draw(TransformPen(ipen, (k, 0, 0, -k, -icx, 0)))
    iw = (bp.bounds[2] - bp.bounds[0]) * k

    data = {"cap": round(cap, 1), "w": round(total, 1), "iCx": round(i_cx, 1),
            "d": pen.getCommands(), "I": {"d": ipen.getCommands(), "w": round(iw, 1)}}
    OUT.write_text("/* Generated by tools/build_wordmark.py from Marcellus (SIL OFL). Do not edit. */\n"
                   "window.LT = window.LT || {};\nLT.WORDMARK = " + json.dumps(data) + ";\n")
    print("wrote", OUT, "cap", cap, "width", round(total), "I centre", round(i_cx), "I width", round(iw))


main()
