#!/usr/bin/env python3
"""Outline the Low Tide wordmark from Gloock (OFL) into marketing/steam/wordmark.js.

Usage: python3 build_wordmark.py [path/to/Gloock-Regular.ttf]
With no argument the font is fetched from Google Fonts.
Requires: pip install fonttools
"""
import json, re, sys, urllib.request
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

TRACK = 70  # extra letter-spacing in font units (upm 1000 after normalising)
OUT = Path(__file__).resolve().parent.parent / "wordmark.js"


def fetch_font() -> Path:
    css = urllib.request.urlopen(urllib.request.Request(
        "https://fonts.googleapis.com/css2?family=Gloock",
        headers={"User-Agent": "Mozilla/5.0"})).read().decode()
    url = re.search(r"url\((https://[^)]+\.ttf)\)", css).group(1)
    dst = Path("/tmp/Gloock-Regular.ttf")
    dst.write_bytes(urllib.request.urlopen(url).read())
    return dst


def outline(font: TTFont, text: str):
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    k = 1000 / upm
    x = 0.0
    pen = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    for i, ch in enumerate(text):
        name = cmap[ord(ch)]
        # y is flipped so the baseline is y=0 and the cap line is negative (SVG space)
        tp = TransformPen(pen, (k, 0, 0, -k, x, 0))
        gs[name].draw(tp)
        x += gs[name].width * k + (TRACK if i < len(text) - 1 else 0)
    return pen.getCommands(), x


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else fetch_font()
    font = TTFont(path)
    cap = font["OS/2"].sCapHeight * 1000 / font["head"].unitsPerEm
    low_d, low_w = outline(font, "LOW")
    tide_d, tide_w = outline(font, "TIDE")
    data = {"cap": round(cap, 1), "LOW": {"d": low_d, "w": round(low_w, 1)},
            "TIDE": {"d": tide_d, "w": round(tide_w, 1)}}
    OUT.write_text("/* Generated by tools/build_wordmark.py from Gloock (SIL OFL). Do not edit. */\n"
                   "window.LT = window.LT || {};\nLT.WORDMARK = " + json.dumps(data) + ";\n")
    print("wrote", OUT, "cap", cap, "LOW", low_w, "TIDE", tide_w)


main()
